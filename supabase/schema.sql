-- Commission Studio: owner-only data model
-- Run in the Supabase SQL Editor after creating your project.
-- Create your owner account first; owner_id is always tied to auth.uid().

create table if not exists public.commissions (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  month text,
  client text,
  contact text,
  status text,
  sketch boolean,
  line boolean,
  color boolean,
  payment text,
  type text,
  scale text,
  characters numeric,
  price numeric,
  paid numeric,
  usage text,
  sample_permission text,
  credit text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists commissions_owner_month_idx
  on public.commissions (owner_id, month);

alter table public.commissions enable row level security;

drop policy if exists "Owner can read own commissions" on public.commissions;
create policy "Owner can read own commissions"
  on public.commissions for select to authenticated
  using (auth.uid() = owner_id);

drop policy if exists "Owner can insert own commissions" on public.commissions;
create policy "Owner can insert own commissions"
  on public.commissions for insert to authenticated
  with check (auth.uid() = owner_id);

drop policy if exists "Owner can update own commissions" on public.commissions;
create policy "Owner can update own commissions"
  on public.commissions for update to authenticated
  using (auth.uid() = owner_id)
  with check (auth.uid() = owner_id);

drop policy if exists "Owner can delete own commissions" on public.commissions;
create policy "Owner can delete own commissions"
  on public.commissions for delete to authenticated
  using (auth.uid() = owner_id);

